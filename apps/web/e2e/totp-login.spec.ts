import { signInAdmin } from './helpers/session'
import { test, expect } from '@playwright/test'
import { createHmac } from 'node:crypto'
import jsQR from 'jsqr'

// Only disposable test credentials are used; never retain QR/recovery-code traces.
test.use({ trace: 'off', screenshot: 'off', video: 'off' })
function totp(secret: string, step: number) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'
  const bits = [...secret.replace(/=+$/, '')].map(char => alphabet.indexOf(char).toString(2).padStart(5, '0')).join('')
  const key = Buffer.from(bits.match(/.{8}/g)!.map(byte => parseInt(byte, 2)))
  const counter = Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(step))
  const hash = createHmac('sha1', key).update(counter).digest()
  return ((hash.readUInt32BE(hash[19] & 15) & 0x7fffffff) % 1_000_000).toString().padStart(6, '0')
}

test('Scan QR, confirm TOTP, then sign in through a separate MFA challenge', async ({ page }) => {
  test.setTimeout(120_000)
  if (process.env.FERRIX_E2E_DISPOSABLE !== '1') throw new Error('Use the disposable Services UI runner.')
  const base = process.env.FERRIX_E2E_URL!
  expect(new URL(base).port).not.toBe('5173')
  const password = 'A long disposable browser test password!'
  await signInAdmin(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/security')
  await page.getByRole('button', { name: 'Set up authenticator', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Set up authenticator', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Set up authenticator', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Confirm password', { exact: true }).fill(password)
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click()
  const qr = page.getByRole('img', { name: 'Scan to set up Ferrix two-factor authentication' })
  await expect(qr).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  // Decode the real rendered SVG; verifying an image exists would miss unusable QR codes.
  const pixels = await qr.evaluate(async svg => {
    const image = new Image()
    image.src = 'data:image/svg+xml;base64,' + btoa(new XMLSerializer().serializeToString(svg))
    await image.decode()
    const canvas = document.createElement('canvas'); canvas.width = 200; canvas.height = 200
    const context = canvas.getContext('2d')!; context.drawImage(image, 0, 0, 200, 200)
    return Array.from(context.getImageData(0, 0, 200, 200).data)
  })
  const decoded = jsQR(new Uint8ClampedArray(pixels), 200, 200)
  expect(Boolean(decoded)).toBe(true)
  const uri = new URL(decoded!.data)
  expect(uri.protocol).toBe('otpauth:')
  expect(uri.hostname).toBe('totp')
  expect(uri.searchParams.get('issuer')).toBe('Ferrix')
  const secret = uri.searchParams.get('secret')!
  expect(Boolean(secret)).toBe(true)
  const step = Math.floor(Date.now() / 30_000)
  await page.getByLabel('Authenticator code', { exact: true }).fill(totp(secret, step))
  await page.getByRole('button', { name: 'Enable two-factor authentication', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Save your recovery codes', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  const recovery = (await page.locator('pre').innerText()).split('\n')
  expect(recovery.length).toBe(8)
  await dialog.getByRole('button', { name: 'I saved my codes', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await page.request.post('/api/v1/auth/sign-out', { headers: { Origin: base } })).status()).toBe(204)
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('services-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Two-factor authentication', exact: true })).toBeVisible()
  await expect(page.getByLabel('Password', { exact: true })).toHaveCount(0)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  await page.getByRole('button', { name: 'Use a recovery code', exact: true }).click()
  await page.getByLabel('Recovery code', { exact: true }).fill(recovery[0])
  await page.getByRole('button', { name: 'Verify and sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(200)
  await page.request.post('/api/v1/auth/sign-out', { headers: { Origin: base } })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('services-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page.getByLabel('Authenticator code', { exact: true })).toBeFocused()
  // The next time step is in the allowed clock-skew window, without sleeping in tests.
  await page.getByLabel('Authenticator code', { exact: true }).fill(totp(secret, Math.max(step + 1, Math.floor(Date.now() / 30_000))))
  await page.getByRole('button', { name: 'Verify and sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.request.post('/api/v1/auth/sign-out', { headers: { Origin: base } })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('services-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await page.getByRole('button', { name: 'Back to sign in', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
  expect((await page.request.post('/api/v1/auth/sign-in/verify', { headers: { Origin: base }, data: { code: '123456' } })).status()).toBe(410)
  await page.getByLabel('Email', { exact: true }).fill('services-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await page.route('**/api/v1/auth/sign-in/verify', route => route.fulfill({ status: 410, json: { error: 'Verification expired. Sign in again.' } }))
  await page.getByLabel('Authenticator code', { exact: true }).fill('123456')
  await page.getByRole('button', { name: 'Verify and sign in', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
  await expect(page.getByText('Verification expired. Sign in again.', { exact: true })).toBeVisible()
  await page.unroute('**/api/v1/auth/sign-in/verify')
  expect((await page.request.post('/api/v1/auth/sign-in', { headers: { Origin: base }, data: { email: 'services-ui@example.com', password } })).status()).toBe(200)
  expect((await page.request.post('/api/v1/auth/sign-in/verify', { headers: { Origin: base }, data: { code: recovery[1] } })).status()).toBe(200)
  expect((await page.request.post('/api/v1/auth/mfa/disable', { headers: { Origin: base }, data: { password, code: recovery[2] } })).status()).toBe(204)

})
