import { signInAdmin } from './helpers/session'
import { test, expect } from '@playwright/test'

test('Create Service offers only Application and Database', async ({ page, request }) => {
  test.setTimeout(180_000)
  const base = process.env.FERRIX_E2E_URL
  if (!base || process.env.FERRIX_E2E_DISPOSABLE !== '1') throw new Error('Use an isolated preview database with FERRIX_E2E_URL and FERRIX_E2E_DISPOSABLE=1.')
  expect(new URL(base).hostname).toBe('127.0.0.1')
  expect(new URL(base).port).not.toBe('5173')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await signInAdmin(page)
  await page.goto('/projects')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Docker UI test')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await page.getByRole('link', { name: 'Docker UI test', exact: true }).click()
  await expect(page.getByRole('button', { name: 'production', exact: true })).toBeVisible()
  const projectUrl = page.url()
  async function checkControls() {
    const serviceId = page.url().split('/').pop()!
    const before = await (await page.request.get(`/api/v1/services/${serviceId}/runtime`)).json()
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm stop', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeEnabled({ timeout: 30_000 })
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Reload', exact: true })).toBeEnabled({ timeout: 30_000 })
    await page.getByRole('button', { name: 'Reload', exact: true }).click()
    await expect(page.getByText('Service restarted using its deployed configuration.', { exact: true })).toBeVisible({ timeout: 30_000 })
    const after = await (await page.request.get(`/api/v1/services/${serviceId}/runtime`)).json()
    expect(after.container_id ?? after.containers.map((container: {id: string}) => container.id)).toEqual(before.container_id ?? before.containers.map((container: {id: string}) => container.id))
    await page.getByRole('tab', { name: 'Environment', exact: true }).click()
    await expect(page.getByLabel('Environment variables', { exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Logs', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Container logs', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  }

  await page.getByRole('button', { name: 'Project Environment', exact: true }).click()
  await page.getByLabel('Environment name', { exact: true }).fill('staging')
  await page.getByRole('button', { name: 'Create environment', exact: true }).click()
  await page.getByRole('button', { name: 'staging', exact: true }).click()
  await page.getByRole('menuitem', { name: 'production', exact: true }).click()

  await page.getByRole('button', { name: 'Create Service', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Application', exact: true }).click()
  await page.getByLabel('Application name', { exact: true }).fill('nginx')
  await expect(page.getByLabel('Docker image', { exact: true })).toHaveValue('nginx:alpine')
  await page.getByLabel('Environment variables', { exact: true }).fill('FERRIX_UI_TEST=literal-value')
  await page.getByRole('button', { name: 'Create Application', exact: true }).click()
  await page.getByRole('link', { name: 'nginx', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'nginx', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Configuration', exact: true }).click()
  await expect(page.getByLabel('Environment variables', { exact: true })).toHaveValue('FERRIX_UI_TEST=literal-value')
  await expect(page.getByRole('heading', { name: 'Service configuration', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Deploy', exact: true }).click()
  await expect(page.getByText('succeeded · Active', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  const applicationAddress = page.getByRole('link', { name: /^Open http:\/\/127\.0\.0\.1:/ })
  await expect(applicationAddress).toBeVisible({ timeout: 60_000 })
  expect(await (await request.get((await applicationAddress.getAttribute('href'))!)).text()).toContain('Welcome to nginx')
  await page.getByRole('button', { name: 'Container logs', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Container logs', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await checkControls()

  // A second successful deployment makes the first version selectable for rollback.
  await page.getByRole('button', { name: 'Deploy', exact: true }).click()
  const enabledRollback = page.locator('button:not([disabled])').filter({ hasText: /^Rollback$/ }).first()
  await expect(enabledRollback).toBeVisible({ timeout: 60_000 })
  await enabledRollback.click()
  const rollbackDialog = page.getByRole('dialog', { name: 'Rollback nginx?', exact: true })
  await expect(rollbackDialog).toContainText('environment variables')
  await rollbackDialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await enabledRollback.click()
  await rollbackDialog.getByRole('button', { name: 'Confirm rollback', exact: true }).click()
  await expect(page.getByText('succeeded · Rollback · Active', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.screenshot({ path: '/private/tmp/ferrix-rollback-history.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  expect(await (await request.get((await applicationAddress.getAttribute('href'))!)).text()).toContain('Welcome to nginx')

  await page.goto(projectUrl)
  await page.getByRole('button', { name: 'Create Service', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Database', exact: true }).click()
  const databaseDialog = page.getByRole('dialog', { name: 'Databases', exact: true })
  await expect(databaseDialog).toBeVisible()
  await expect(databaseDialog.getByRole('radio')).toHaveCount(4)
  await expect(databaseDialog.getByRole('radio', { name: 'MySQL', exact: true })).toHaveCount(0)
  await expect(databaseDialog.getByRole('radio', { name: 'libSQL', exact: true })).toHaveCount(0)
  await databaseDialog.getByRole('radio', { name: 'Redis', exact: true }).check()
  await expect(databaseDialog.getByLabel('Database name', { exact: true })).toHaveCount(0)
  await databaseDialog.getByRole('radio', { name: 'MongoDB', exact: true }).check()
  await expect(databaseDialog.getByLabel('Database name', { exact: true })).toBeVisible()
  await databaseDialog.getByRole('radio', { name: 'MariaDB', exact: true }).check()
  await databaseDialog.getByRole('radio', { name: 'PostgreSQL', exact: true }).check()
  await page.screenshot({ path: '/private/tmp/ferrix-databases-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/ferrix-databases-mobile.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Service name', { exact: true }).fill('PostgreSQL UI')
  await page.getByRole('button', { name: 'Create Database', exact: true }).click()
  await page.getByRole('link', { name: 'PostgreSQL UI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'PostgreSQL UI', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Deploy', exact: true }).click()
  await page.getByRole('tab', { name: 'Deployments', exact: true }).click()
  await expect(page.getByText('succeeded · Active', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await checkControls()
  await page.getByRole('button', { name: 'Connection details', exact: true }).click()
  await expect(page.getByLabel('Connection URL', { exact: true })).toHaveAttribute('type', 'password')
  await expect(page.getByLabel('Connection URL', { exact: true })).toHaveValue(/^postgresql:\/\//)
  await page.getByRole('button', { name: 'Configuration', exact: true }).click()
  await expect(page.getByLabel('Username', { exact: true })).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()

  const databaseUrl = page.url()
  await page.getByRole('tab', { name: 'Backups', exact: true }).click()
  await page.getByRole('button', { name: 'Backup now', exact: true }).click()
  await expect(page.getByText('Backup completed.', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  const restoreDialog = page.getByRole('dialog', { name: 'Restore to a new database', exact: true })
  await restoreDialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await restoreDialog.getByLabel('New service name', { exact: true }).fill('PostgreSQL restored UI')
  await restoreDialog.getByRole('button', { name: 'Restore backup', exact: true }).click()
  await expect(page.getByText('Restore completed. The new database service is ready.', { exact: true })).toBeVisible({ timeout: 60_000 })
  await page.screenshot({ path: '/private/tmp/ferrix-backups-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/ferrix-backups-mobile.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('link', { name: 'PostgreSQL restored UI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'PostgreSQL restored UI', exact: true })).toBeVisible()
  await page.goto(databaseUrl)

  await page.screenshot({ path: '/private/tmp/ferrix-service-controls-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/ferrix-service-controls-mobile.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })

  await page.goto(projectUrl)
  await page.getByRole('button', { name: 'All types', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Database', exact: true }).click()
  await expect(page.getByRole('link', { name: 'PostgreSQL UI', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'nginx', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Database', exact: true }).click()
  await page.getByRole('menuitem', { name: 'All types', exact: true }).click()
  await page.getByLabel('Filter services', { exact: true }).fill('nginx')
  await expect(page.getByRole('link', { name: 'nginx', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'PostgreSQL UI', exact: true })).toHaveCount(0)
  await page.getByLabel('Filter services', { exact: true }).fill('')
  await page.getByRole('button', { name: 'Create Service', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Application', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Compose', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitem', { name: 'Static Website', exact: true })).toHaveCount(0)
  await page.screenshot({ path: '/private/tmp/ferrix-services-desktop.png', fullPage: true, animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/ferrix-services-mobile.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  // Cancellation and exact-name confirmation protect against accidental deletion.
  await page.getByRole('button', { name: 'Delete nginx', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Delete service', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('link', { name: 'nginx', exact: true })).toBeVisible()
  for (const name of ['nginx', 'PostgreSQL UI', 'PostgreSQL restored UI']) {
    await page.getByRole('button', { name: `Delete ${name}`, exact: true }).click()
    await page.getByLabel('Type the service name to confirm', { exact: true }).fill(name)
    if (name !== 'nginx') {
      await page.getByRole('button', { name: 'Keep data volumes', exact: true }).click()
      await page.getByRole('menuitem', { name: 'Permanently delete data', exact: true }).click()
    }
    await page.getByRole('button', { name: 'Delete service', exact: true }).click()
    await expect(page.getByRole('link', { name, exact: true })).toHaveCount(0)
    await expect(page.getByRole('heading', { name: `Delete ${name}?`, exact: true })).toHaveCount(0)
  }
  await expect(page.getByText('No services in production', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
