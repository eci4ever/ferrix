import { test, expect } from '@playwright/test'
import { writeFile } from 'node:fs/promises'

test('project → environment → Docker application → Nginx deployment', async ({ page, request }) => {
  const base = process.env.FERRIX_E2E_URL
  if (!base || process.env.FERRIX_E2E_DISPOSABLE !== '1') throw new Error('Use FERRIX_E2E_URL and FERRIX_E2E_DISPOSABLE=1 with an isolated preview database, never a user database.')
  expect(new URL(base).hostname).toBe('127.0.0.1')
  expect(new URL(base).port).not.toBe('5173')
  const setup = await request.get('/api/v1/auth/setup')
  expect((await setup.json()).setup_required).toBe(true)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/signup')
  await page.getByLabel('Name', { exact: true }).fill('Deployment UI test')
  await page.getByLabel('Email', { exact: true }).fill('deploy-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill('A long disposable browser test password!')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/projects')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Docker UI test')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await page.getByRole('link', { name: 'Docker UI test', exact: true }).click()
  await expect(page.getByRole('button', { name: 'production', exact: true })).toBeVisible()
  const projectId = page.url().split('/').at(-1)!
  await page.getByRole('button', { name: 'Environment', exact: true }).click()
  await page.getByLabel('Environment name', { exact: true }).fill('staging')
  await page.getByRole('button', { name: 'Create environment', exact: true }).click()
  await expect(page.getByRole('button', { name: 'staging', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Application', exact: true }).click()
  await page.getByLabel('Application name', { exact: true }).fill('nginx')
  await expect(page.getByLabel('Docker image', { exact: true })).toHaveValue('nginx:alpine')
  await page.getByLabel('Environment variables', { exact: true }).fill('FERRIX_UI_TEST=literal-value')
  await page.getByRole('button', { name: 'Create application', exact: true }).click()
  await page.getByRole('link', { name: 'Open', exact: true }).click()
  const applicationId = page.url().split('/').at(-1)!
  await writeFile('/private/tmp/ferrix-deploy-ui-project.json', JSON.stringify({ projectId, applicationId }))
  await expect(page.getByRole('heading', { name: 'nginx', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Configuration', exact: true }).click()
  await expect(page.getByLabel('Environment variables', { exact: true })).toHaveValue('FERRIX_UI_TEST=literal-value')
  await expect(page.getByRole('button', { name: 'Deploy', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Deploy', exact: true }).click()
  const open = page.getByRole('link', { name: /^Open http:\/\/127\.0\.0\.1:/ })
  await expect(open).toBeVisible({ timeout: 60_000 })
  const address = await open.getAttribute('href')
  expect(address).toBeTruthy()
  const nginx = await request.get(address!)
  expect(nginx.ok()).toBe(true)
  expect(await nginx.text()).toContain('Welcome to nginx')
  await expect(page.getByText('succeeded', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Container logs', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Container logs', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/ferrix-deployment-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'nginx', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/ferrix-deployment-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
