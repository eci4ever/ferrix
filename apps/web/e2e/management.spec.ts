import { test, expect } from '@playwright/test'

test.use({ trace: 'off', screenshot: 'off', video: 'off' })
test('Manage users and organization with real permissions and confirmation dialogs', async ({ page, browser }) => {
  test.setTimeout(120_000)
  if (process.env.FERRIX_E2E_DISPOSABLE !== '1') throw new Error('Use the disposable Services UI runner.')
  const base = process.env.FERRIX_E2E_URL!
  expect(new URL(base).port).not.toBe('5173')
  async function userAction(name: string) { await page.getByRole('button', { name: /^Actions for / }).click(); await page.getByRole('menuitem', { name, exact: true }).click() }
  const password = 'A long disposable browser test password!'
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill('services-ui@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/organization')
  await expect(page.getByRole('button', { name: 'Delete organization', exact: true })).toBeDisabled()
  await expect(page.getByText('The default organization cannot be deleted.', { exact: true })).toBeVisible()
  await page.getByLabel('New organization name', { exact: true }).fill('Management browser')
  await page.getByRole('button', { name: 'Create organization', exact: true }).click()
  await page.getByRole('button', { name: 'Management browser (owner)', exact: true }).click()
  await expect(page.getByLabel('Organization name', { exact: true })).toHaveValue('Management browser')
  await page.getByLabel('Organization name', { exact: true }).fill('Management lab')
  await page.getByRole('button', { name: 'Save organization', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Management lab (owner)', exact: true })).toBeVisible()
  await page.getByLabel('Invitation email', { exact: true }).fill('managed-browser@example.com')
  await page.getByRole('button', { name: 'Invite member', exact: true }).click()
  const tokenAlert = page.getByRole('alert').filter({ hasText: 'Invitation token' })
  await expect(tokenAlert).toBeVisible()
  const oldToken = await tokenAlert.locator('code').innerText()
  const invitation = page.getByRole('table', { name: 'Invitations', exact: true }).getByRole('row').filter({ hasText: 'managed-browser@example.com' })
  await invitation.getByRole('button', { name: 'Regenerate', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const token = await tokenAlert.locator('code').innerText()
  expect(token === oldToken).toBe(false)
  await tokenAlert.getByRole('button', { name: 'Dismiss token', exact: true }).click()
  const member = await browser.newContext({ baseURL: base })
  try {
    const registration = { name: 'Managed browser user', email: 'managed-browser@example.com', password, token: oldToken }
    expect((await member.request.post('/api/v1/auth/accept-invitation', { headers: { Origin: base }, data: registration })).status()).toBe(401)
    expect((await member.request.post('/api/v1/auth/accept-invitation', { headers: { Origin: base }, data: { ...registration, token } })).status()).toBe(200)
    await page.reload()
    await page.getByLabel('Search Members', { exact: true }).fill('managed-browser@example.com')
    await expect(page.getByRole('table', { name: 'Members', exact: true }).getByText('Managed browser user', { exact: true })).toBeVisible()
    await page.goto('/admin')
    await page.getByLabel('Search Users', { exact: true }).fill('managed-browser@example.com')
    await page.getByRole('button', { name: 'Details', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('table', { name: 'User organizations', exact: true })).toContainText('Management lab')
    await expect(page.getByRole('dialog').getByRole('table', { name: 'User sessions', exact: true }).getByRole('row')).toHaveCount(2)
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
    await userAction('Ban')
    await page.getByRole('dialog').getByLabel('Ban reason', { exact: true }).fill('Browser temporary ban')
    const expiry = await page.evaluate(() => { const date = new Date(Date.now() + 3_600_000); return new Date(date.getTime() - date.getTimezoneOffset() * 60_000).toISOString().slice(0, 16) })
    await page.getByRole('dialog').getByLabel('Ban expiry (optional)', { exact: true }).fill(expiry)
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText('Browser temporary ban', { exact: true })).toBeVisible()
    expect((await member.request.get('/api/v1/auth/session')).status()).toBe(401)
    await userAction('Unban')
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('table', { name: 'Users', exact: true })).toContainText('Active')
    await userAction('Make admin')
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('table', { name: 'Users', exact: true })).toContainText('admin')
    await userAction('Make user')
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByRole('table', { name: 'Users', exact: true })).toContainText(registration.email)
    await page.screenshot({ path: '/private/tmp/ferrix-users-management-mobile.png', fullPage: true })
    await page.goto('/organization')
    const members = await (await page.request.get('/api/v1/auth/members')).json()
    const target = members.find((user: {email: string}) => user.email === 'managed-browser@example.com')
    await page.getByLabel('New owner', { exact: true }).selectOption(target.id)
    await page.getByRole('button', { name: 'Transfer ownership', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Transfer ownership', exact: true })).toHaveCount(0)
    const login = { email: registration.email, password }
    expect((await member.request.post('/api/v1/auth/sign-in', { headers: { Origin: base }, data: login })).status()).toBe(200)
    const admin = await (await page.request.get('/api/v1/auth/session')).json()
    expect((await member.request.post('/api/v1/auth/organizations/transfer', { headers: { Origin: base }, data: { user_id: admin.user_id } })).status()).toBe(204)
    const memberPage = await member.newPage()
    await memberPage.goto('/organization')
    await memberPage.getByRole('button', { name: 'Leave organization', exact: true }).click()
    await memberPage.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(memberPage).toHaveURL(/\/login$/)
    await page.goto('/admin')
    await page.getByLabel('Search Users', { exact: true }).fill(registration.email)
    await userAction('Delete')
    await page.getByRole('dialog').getByLabel(`Type ${registration.email} to confirm`, { exact: true }).fill(registration.email)
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('table', { name: 'Users', exact: true })).not.toContainText(registration.email)
    await page.goto('/organization')
    await page.getByRole('button', { name: 'Delete organization', exact: true }).click()
    await page.getByRole('dialog').getByLabel('Type Management lab to confirm', { exact: true }).fill('Management lab')
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
    await expect(page).toHaveURL(/\/login$/)
  } finally { await member.close() }
})
